# 1. Користувач вводить результат спортсмена по стрибках у висоту. Виведіть на екран чи вдалось побити рекорд
# Магучіх. Якщо результат такий самий то вивести фразу “рекорд повторено”
record = 2.10

result = float(input("Введіть результат стрибка: "))

if result > record:
    print("Рекорд Магучіх побито!")
elif result == record:
    print("Рекорд повторено")
else:
    print("Рекорд не побито")

