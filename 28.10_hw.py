# 4. Користувач вводить ширину та висоту прямокутника.
# Програма повинна вивести площу та периметр. Зробіть цю задачу за допомогою ШІ Інтерн
width = float(input("Введіть ширину прямокутника: "))
height = float(input("Введіть висоту прямокутника: "))

area = width * height
perimeter = 2 * (width + height)

