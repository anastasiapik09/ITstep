# 1. Користувач вводить ціну за одиницю товару та кількість
# товару. Якщо загальна сума більша за 500грн або купівля
# оптом(більше 10 шт), застосувати знижку 10%
price = float(input("Введіть ціну за одиницю товару: "))
quantity = int(input("Введіть кількість товару: "))

total = price * quantity

if total > 500 or quantity > 10:
    discount = total * 0.1
else:
    discount = 0

final_price = total - discount

print("Загальна сума:", total, "грн")
print("Знижка:", discount, "грн")
print("Сума до сплати:", final_price, "грн")

