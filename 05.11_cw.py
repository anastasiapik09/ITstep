# 2. total_items + 1 не змінює значення змінної. Потрібно написати total_items += 1
total_items = 0

print("Додайте товари. Для завершення введіть 'stop'.")

while True:
    item = input("Введіть товар: ")

    if item == "stop":
        break

    total_items += 1

print("Підрахунок завершений")
print(f"Всього товарів додано: {total_items}")

# 6. Напишіть програму для введення пароля від банкомату.
# У користувача є лише три спроби
# В кінці виведіть чи вдалось правильно ввести пароль
correct_password = "1234"
attempts = 0

while attempts < 3:
    password = input("Введіть пароль: ")
    attempts += 1

    if password == correct_password:
        print("Пароль введено правильно!")
        break

if password == correct_password:
    print("Вхід успішний!")

else:
    print("Спроби закінчилися. Пароль введено неправильно")