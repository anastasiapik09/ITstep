# 1. Користувач вводить свої ім’я та вік. Якщо введено
# від’ємне число то попросити ще раз ввести правильний вік
# поки не буде введено додатнє число.
# В кінці вивести привітання “Привіт Джон. Тобі 36  років”
name = input("Введіть своє ім'я: ")

age = int(input("Введіть свій вік: "))

while age < 0:
    print("Вік не може бути від'ємним!")
    age = int(input("Введіть правильний вік: "))

print(f"Привіт {name}. Тобі {age}")

# 2. Користувач вводить суму грошей, яку він хоче
# відкласти. Далі кожного дня користувач вводить суму, яку
# він кладе в скарбничку.
# Програма зупиняється коли грошей достатньо.
# Виправте помилку в коді

# Виправлення: Перенесли total = 0 перед циклом while, щоб загальна сума не обнулялася
# кожного дня.
goal = float(input("Цільова сума? "))

total = 0

while True:
    daily_amount = float(input("Сьогоднішній вклад? "))
    total += daily_amount

    if total >= goal:
        break

print(f"Мету досягнуто! У скарбничці {total} грн.")

# 3. Користувач вводить довжину в метрах. Покажіть її у
# ● Ярдах(1 ярд = 0,9144 метра)
# ● Футах(1 фут = 0,3048 метра)
# В кінці спитайте користувача чи продовжувати роботу програми.
while True:
    meters = float(input("Введіть довжину в метрах: "))

    yards = meters / 0.9144
    feet = meters / 0.3048

    print(f"Довжина в ярдах: {yards}")
    print(f"Довжина у футах:  {feet}")

    answer = input("Бажаєте продовжити роботу програми? (так/ні): ")

    if answer == "ні":
        break

print("Програму завершено")

# 4. У завданні 2 ще виведіть кількість днів за яку була
# зібрана потрібна сума.
goal = float(input("Цільова сума? "))

total = 0
days = 0

while True:
    daily_amount = float(input("Сьогоднішній вклад? "))
    total += daily_amount
    days += 1

    if total >= goal:
        break

print(f"Мету досягнуто! У скарбничці {total} грн.")
print(f"Кількість днів: {days}")

