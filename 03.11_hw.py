# 1. Потрібно порахувати суму чисел в діапазоні, але
# програма виводить не те що треба(загальна сума має бути 15), виправіть помилку

# Потрібно використовувати total += number, щоб додавати числа до загальної суми.

total = 0

for number in range(1, 6):
    total += number

print(f"Сума: {total}")

# 2. Користувач вводить два числа(початок та кінець
# діапазону). Пройдіться по всіх числах з цього діапазону та
# виведіть такий результат:
# ● якщо число ділиться на 3 – написати Fizz
# ● якщо число ділиться на 5 – написати Buzz
# ● якщо число ділиться на 3 i на 5 – написати FizzBuzz
# ● інакше вивести саме число
start = int(input("Введіть початок діапазону: "))
end = int(input("Введіть кінець діапазону: "))

for num in range(start, end + 1):
    if num % 3 == 0 and num % 5 == 0:
        print("FizzBuzz")
    elif num % 3 == 0:
        print("Fizz")
    elif num % 5 == 0:
        print("Buzz")
    else:
        print(num)

# 3. Напишіть програму яка протягом 5 робочих днів запитує
# в кур’єра кількість доставлених замовлень за кожен день.
# В кінці виведіть загальну кількість доставок за робочий
# тиждень та чи виконано тижневу норму в 50 доставок
total = 0

for day in range(1, 6):
    deliveries = int(input(f"Введіть кількість доставок за день {day}: "))
    total += deliveries

print(f"Загальна кількість доставок за тиждень: {total}")

if total >= 50:
    print("Тижневу норму виконано!")
else:
    print("Тижневу норму не виконано!")
