# Інша швидкість – побажати гарної подорожі.
speed = float(input("Введіть швидкість (км/год): "))

if speed > 90:
    place = input("Де ви їдете: місто чи траса? ")

    if place == "місто":
        print("Вам загрожує штраф!")
    elif place == "траса":
        print("Увага! Перевищення швидкості!")

elif speed < 20:
    age = int(input("Скільки років вашій машині? "))

    if age > 15:
        print("Рекомендуємо купити нову машину")
    else:
        print("Рекомендуємо поїхати на СТО")

else:
    print("Гарної подорожі!")