# 1. Щоб створити одну глиняну фігурку треба 130 грам глини.
# Користувач вводить масу глини в кілограмах. Виведіть скільки фігурок
# він зможе зробити.

#Вводимо масу глини в кілограмах
clay = float(input("Ввеідть масу глини (кг): "))

#Кількість грамів глини для однієї фігурки
clay_per_figure = 130

#Переводимо кілограми в грами
clay *= 1000

#Обчислюємо кількість фігурок
figures = clay // clay_per_figure

#Виводимо результат
print(f"Можна зробити: {figures} фігурок")

# 2. Троє друзів пішли на рибалку. Програма отримує
# кількість риби яку зловив кожен рибалка.
fish1 = int(input("Скільки зловив перший друг: "))
fish2 = int(input("Скільки зловив другий друг: "))
fish3 = int(input("Скільки зловив третій друг: "))

average = (fish1 + fish2 + fish3) / 3

max_fish = max(fish1, fish2, fish3)

print("Середній улов на людину: ", average)
print("Найбільший улов: ", max_fish)

# 3. У кінотеатрі можна замовити квитки онлайн. Користувач вводить бюджет. Виведіть скільки людей
